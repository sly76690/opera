# Each sound only lists what differs from the defaults: Opera fills in the rest when it loads it.
# Every sound is programmed from scratch on Opera, from the textbook FM recipes (a 14:1 tine on an electric piano,
# a modulator swelling after its carrier for brass, 3.5:1 and 1.41:1 bells, a feedback saw, odd harmonics from 2:1
# for reeds); no patch of any other instrument is copied.
# LEVEL (patchLevel) comes from tools/levels.json, measured by the smoke tests (tools/niveaux.py): every sound plays
# equally loud, whatever its algorithm and envelopes.
# Usage:  python3 tools/sons.py   (the order of the BANK / PATCH keys is in Source/FactoryBank.h)
import os, glob, json, math
from xml.sax.saxutils import quoteattr

def op(n, ratio=1, det=0, level=0, vel=.3, ks=0, t=(.003, .4, 1.5, .35), l=(1, .75, .6, 0), fixed=None):
    """One operator: a frequency ratio (0.5 to 31, any value: stored as the RATIO stop and FINE), detune in cents,
    level, velocity, key scaling, the four envelope times (s) and levels. fixed: a frequency in Hz instead (FIX)."""
    p = "op%d" % n
    if fixed:   # FIX: 32 stops a third of an octave apart from 16 Hz; FINE (x0.26) moves between them
        stop = max(0, min(31, int(math.floor(3 * math.log2(fixed / 16.)))))
        coarse, fine, fix = stop, min(.99, (fixed / (16. * 2 ** (stop / 3.)) - 1) / .26), 1
    elif ratio < 1:
        coarse, fine, fix = 0, ratio / .5 - 1, 0
    else:
        coarse = int(math.floor(ratio + 1e-6)); fine, fix = ratio / coarse - 1, 0
    d = {p + "coarse": coarse, p + "fine": round(fine, 4), p + "fixed": fix, p + "detune": det, p + "level": level, p + "vel": vel, p + "keyscale": ks}
    for k in range(4): d[p + "t%d" % (k + 1)] = t[k]; d[p + "l%d" % (k + 1)] = l[k]
    return d

def sound(algorithm, *ops, **rest):
    d = {"algorithm": algorithm - 1}
    for o in ops: d.update(o)
    d.update(rest); return d

